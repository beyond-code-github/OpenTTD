"""Splits PSG 197's raw shape (psg197.shape-raw.txt) into the Shape-level projection and V's steps (D396). Run: python3 -I /home/pete/OpenTTD/.claude/ng1/docs/junction-tool/wip/probes/e1/split_shape.py"""
import re, sys
ROOT = '/home/pete/OpenTTD/.claude/ng1'
RAW = ROOT + '/docs/junction-tool/wip/probes/e1/psg197.shape-raw.txt'
TOP = ROOT + '/tools/junction/topologies/psg197.txt'
OUT_SHAPE = ROOT + '/tools/junction/topologies/psg197.shape.txt'
OUT_STEPS = ROOT + '/tools/junction/topologies/psg197.steps.txt'
LETTER = {'N': 0, 'E': 2, 'S': 4, 'W': 6}
in_lines, out_lines = set(), {}
for l in open(TOP):
    m = re.match(r'port (\w) (in|out) (\w): (.*)$', l.strip())
    if not m: continue
    names = [x.split('=')[0].strip() for x in m.group(4).split(',')]
    if m.group(2) == 'in': in_lines |= set(names)
    else:
        for n in names: out_lines[n] = LETTER[m.group(3)]
order, shape, at = [], {}, {}
for l in open(RAW):
    l = l.strip()
    m = re.match(r'shape (\w+): (.*)$', l)
    if m: order.append(m.group(1)); shape[m.group(1)] = [int(x) for x in m.group(2).split()]; continue
    m = re.match(r'at (\w+): (.*)$', l)
    if m: at[m.group(1)] = [tuple(x.strip().split('@')) for x in m.group(2).split(',')]; at[m.group(1)] = [(a, int(b)) for a, b in at[m.group(1)]]
for n in order:
    if n in out_lines:
        h, P = shape[n][-1], out_lines[n]
        if (h - P) % 8 != 0:
            for d in (-1, 1):
                if (h + d - P) % 8 == 0:
                    shape[n].append(h + d); print('appended', n, h + d); break
            else:
                print('port end needs more than one eighth:', n); sys.exit(1)
shape_out = ['# PSG 197 shape at Shape\'s level (D396): each stretch monotone from its start to its end heading; V\'s steps are in psg197.steps.txt; generated by docs/junction-tool/wip/probes/e1/split_shape.py.']
steps_out = ['# PSG 197: V\'s sideways steps per stretch (D396), the raw headings of each stretch that is not monotone; with psg197.shape.txt it gives V\'s raw shape; generated by split_shape.py.']
tally, total, turning, ok = {}, 0, 0, True
for n in order:
    raw = shape[n]
    ends = [p for _, p in at.get(n, [])] + [len(raw) - 1]
    proj, newpieces, steps = [raw[0]], [], {}
    start = 0
    for k, e in enumerate(ends):
        seg = raw[start:e + 1]
        to = raw[e]
        wig = sum(abs(seg[i + 1] - seg[i]) for i in range(len(seg) - 1))
        if wig > abs(to - raw[start]):
            steps[k] = seg
            fr = ('port' if n in in_lines else 'node') if k == 0 else 'crossing'
            tt = ('port' if n in out_lines else 'node') if k == len(ends) - 1 else 'crossing'
            steps_out.append('step %s %d: %s  # %s-%s' % (n, k, ' '.join(map(str, seg)), fr, tt))
            tally[fr + '-' + tt] = tally.get(fr + '-' + tt, 0) + 1; total += 1
        while proj[-1] != to: proj.append(proj[-1] + (1 if to > proj[-1] else -1))
        turning += abs(to - raw[start])
        if k + 1 < len(ends): newpieces.append(len(proj) - 1)
        start = e
    shape_out.append('shape %s: %s' % (n, ' '.join(map(str, proj))))
    if n in at:
        shape_out.append('at %s: %s' % (n, ', '.join('%s@%d' % (a, p) for (a, _), p in zip(at[n], newpieces))))
    # self-check: rebuild raw from projection and steps
    pe = newpieces + [len(proj) - 1]
    rebuilt, ps = [proj[0]], 0
    for k, e in enumerate(pe):
        if k in steps: rebuilt += steps[k][1:]
        else: rebuilt += proj[ps + 1:e + 1]
        ps = e
    if rebuilt != raw: ok = False; print('MISMATCH', n)
open(OUT_SHAPE, 'w').write('\n'.join(shape_out) + '\n')
open(OUT_STEPS, 'w').write('\n'.join(steps_out) + '\n')
print('steps', total, 'tally', tally, 'projection turning', turning, 'reconstruction ok', ok)
